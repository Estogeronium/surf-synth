// Text for the "Сборка" tab. Numbers come from hardware/out/sim-summary.json.
import hw from '../hardware-data/hardware.json';
import blocks from '../hardware-data/blocks.svg?raw';

const sim = hw.sim || {};
const lv = (sim.levels || []);
const wv = (sim.waves || []);
const pick = (s, t) => wv.find((w) => w.surf === s && w.tide === t);

export function guideHtml() {
  const w50f = pick(50, 95), w50s = pick(50, 5), w85f = pick(85, 95);
  return `
<h3>Как это работает</h3>
<div class="blocks">${blocks}</div>
<p>Звук делается аналоговой схемой, без микроконтроллера. Транзистор Q1 даёт белый шум (пробой перехода эмиттер-база). Фильтр R9–R12/C9–C11 превращает его в розовый (−3 дБ на октаву). Два мультивибратора (Tide) раз в несколько секунд «бросают монетку»: триггер U5 запоминает случайный бит из шума, вентиль U9 открывает импульс, а RC-цепочка формирует волну — быстрый подъём и долгий спад. Напряжение волны управляет фильтром (U6A, волна звучит ярче на гребне) и усилителями (U6B — основной слой, U7A — пена).</p>

<h3>Порядок сборки</h3>
<ol>
<li>Плата двусторонняя; <b>детали стоят и паяются с задней стороны</b>. Потенциометры, кнопка и светодиод ставятся с <b>лицевой</b> стороны и паяются со стороны деталей, как в большинстве модулей Eurorack.</li>
<li>Сначала низкие детали: резисторы (стоя), диоды, панельки DIP, керамические и плёночные конденсаторы, транзисторы, затем электролиты и крупные плёночные C24/C25, подстроечные RV1/RV2.</li>
<li>Потом потенциометры, кнопка, светодиод, гнездо питания. <b>Микросхемы пока не вставляйте.</b></li>
<li>Подайте 12 В. Нормальные напряжения: V12 ≈ 11,8 В, A12 ≈ 11,6–11,7 В, VB ≈ 5,8–5,9 В на выводах питания панелек. Если нет — ищите короткое замыкание.</li>
<li>Выключите питание, вставьте микросхемы (метка у вывода 1), включите снова. LM386 берите версии N-3/N-4: у N-1 предел 12 В.</li>
</ol>

<h3>Настройка</h3>
<ol>
<li><b>Шум (RV1).</b> Милливольтметр или осциллограф на выход W (U1A, вывод 1): нужно примерно 100–150 мВ среднеквадратичных. Нет шума — замените Q1: у разных экземпляров пробой эмиттера лежит от 6 до 10 В и шум сильно разный.</li>
<li><b>Разброс волн (RV2).</b> Поставьте Surf в середину. RV2 подберите так, чтобы волны шли с паузами. Светодиод показывает гребни. При минимуме Surf должно быть почти тихо, на максимуме — почти непрерывный прибой.</li>
<li><b>Tide</b> — сдвоенный потенциометр, оба движка одним валом. По часовой стрелке волны чаще.</li>
<li><b>Щелчки при волнах.</b> Это смещение нуля в U6: попробуйте другой экземпляр LM13700 или добавьте подстройку смещения (в схему не входит).</li>
</ol>

<h3>Что проверено в симуляции</h3>
<p>Схема на листах — исходник: из неё получены списки соединений и SPICE-модель (ngspice, упрощённые модели ОУ и OTA). Результаты:</p>
<ul>
<li>Режим по постоянному току: V12 ${sim.dc?.V12 ?? '—'} В, A12 ${sim.dc?.A12 ?? '—'} В, VB ${sim.dc?.VB ?? '—'} В, выход усилителя ${sim.dc?.OUTA ?? '—'} В (середина питания).</li>
<li>Розовый фильтр: наклон ${sim.pink?.slope_db_oct ?? '—'} дБ/окт., отклонение ±${sim.pink?.max_dev_db ?? '—'} дБ в диапазоне ${sim.pink?.band ?? ''}.</li>
<li>Срез фильтра U6A: ${(sim.vcf || []).map((v) => `${v.fc_hz} Гц при ${v.vw} В`).join(', ')}. Ручка Tone сдвигает базовый срез от ${sim.tone?.min_hz ?? '—'} до ${sim.tone?.max_hz ?? '—'} Гц.</li>
<li>Уровни: на смесителе ${lv.length ? `${lv[0].mix_mv} мВ в паузе → ${lv[lv.length - 1].mix_mv} мВ на гребне` : '—'}; на динамике ${lv.length ? `${lv[0].spk_v} В → ${lv[lv.length - 1].spk_v} В ср.-кв.` : '—'} (≈ ${lv.length ? (lv[lv.length - 1].spk_v ** 2 / 8).toFixed(2) : '—'} Вт при ручке 80 %).</li>
<li>Мультивибраторы: период ${pick(50, 95)?.periods_s?.join(' и ') ?? '3,5 и 4,5'} с при Tide на максимуме и ${pick(50, 5)?.periods_s?.join(' и ') ?? '8 и 11'} с на минимуме; импульс ≈ 1,2 с.</li>
<li>Волн в минуту при Surf 50 %: ${w50s?.waves_per_min ?? '—'} (медленный Tide) … ${w50f?.waves_per_min ?? '—'} (быстрый); при Surf 85 %: до ${w85f?.waves_per_min ?? '—'}.</li>
</ul>

<h3>Что не проверено</h3>
<ul>
<li>Печатная плата не разведена: расположение деталей здесь — компоновка для наглядности, а не проект платы. Список соединений (<code>hardware/out/surf-synth.net</code>) можно импортировать в KiCad, но я не пробовал его открывать.</li>
<li>Устройство не собиралось. Шум транзистора, смещение нуля OTA и ток потребления взяты из справочных данных, а не измерены.</li>
<li>Модели ОУ и OTA упрощённые: искажения и реальный шум в симуляции не оцениваются.</li>
</ul>`;
}
